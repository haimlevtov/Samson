describe('the voice switch is wired end to end', () => {
  /*
   * WHY a source scan, the same reasoning `the popover clamp` gives above: the
   * painted switch is a sibling selector over a clipped input, and nothing fails
   * when somebody reorders the two spans. The ON state silently stops painting,
   * every check stays green, and the control still toggles — so the bug is
   * invisible to the type system, the linter and the test suite at once.
   *
   * FOUND IN REVIEW of PR #62, which shipped the coupling with no test.
   *
   * AI-NOTE: if the switch ever stops being an adjacent-sibling paint, this is
   *          what tells you to update it — re-point it rather than delete it.
   */
  const css = () => readFileSync(join(ROOT, 'app', 'globals.css'), 'utf8');
  /*
   * RE-POINTED in rework PR 6, as the AI-NOTE above asks. The markup moved from
   * `SessionCoach.tsx` into `src/ui/SpeakSwitch.tsx` when the Coach tab's chat
   * became the second surface to render it — so there is ONE switch to scan now,
   * which both surfaces import, rather than two copies either of which could
   * drift. The test failed on the move, which is the guard doing its job.
   */
  const component = () => readFileSync(join(ROOT, 'src', 'ui', 'SpeakSwitch.tsx'), 'utf8');

  it('paints the checked state from the input that carries it', () => {
    expect(css(), 'the switch no longer paints its ON state').toContain('input:checked + .track');
  });

  it('keeps the input immediately before the track it paints', () => {
    /*
     * `+` is adjacent-sibling, so an element between the two breaks it. JSX
     * comments emit no DOM node and CSS ignores text nodes, so what matters is
     * that no ELEMENT is introduced between them.
     */
    const text = component();
    const role = text.indexOf('role="switch"');
    const track = text.indexOf('className="track"');
    expect(role, 'the switch input is gone').toBeGreaterThan(-1);
    expect(track, 'the painted track is gone').toBeGreaterThan(role);

    /*
     * The first version of this matched the whole span with one lazy regex,
     * and a lazy quantifier BACKTRACKS: inserting a `<span />` between the two
     * let `[\s\S]*?` swallow it and the test passed. Slicing is not clever
     * enough to do that.
     */
    const gap = text
      .slice(text.indexOf('/>', role) + 2, track)
      .replace(/\{\/\*[\s\S]*?\*\/\}/g, '')
      .trim();
    expect(gap, 'an element sits between the switch input and its track').toBe('<span');
  });

  it('keeps the cost sentence out of the label and attached as a description', () => {
    // Inside the label it became part of the accessible name and was announced
    // twice, changing on every press — FOUND IN REVIEW.
    //
    // The id is a PROP now, because two surfaces render the switch — on
    // different routes, so they never collide, but each names its own sentence
    // at most once each and must not collide. So what is asserted is that the
    // description and the sentence are wired to the SAME prop.
    const text = component();
    expect(text).toContain('aria-describedby={describedBy}');
    expect(text).toContain('id={describedBy}');

    // And the sentence sits after the label closes, not inside it.
    expect(text.indexOf('id={describedBy}')).toBeGreaterThan(text.indexOf('</label>'));
  });

  it('is the switch both surfaces render, rather than a copy on each', () => {
    // Two copies of this markup would be two places for the adjacent-sibling
    // paint and the description wiring to drift. Both import the one component.
    for (const surface of [
      join(ROOT, 'app', 'history', '[id]', 'SessionCoach.tsx'),
      join(ROOT, 'app', 'coach', 'CoachBox.tsx'),
    ]) {
      const text = readFileSync(surface, 'utf8');
      expect(text, surface).toContain('<SpeakSwitch');
      expect(text, surface).not.toContain('role="switch"');
    }
  });
});

describe('ADR 0009 and ADR 0017 — application code never selects an achievement predicate', () => {
  /*
   * WHY: `achievements_read_visible` grants the ROW, and `predicate` is a column
   * on it — the SQL `evaluate_achievements` runs. A `select('*')` on that table
   * typechecks, renders correctly, and hands every visible badge's SQL to the
   * page. The badge catalogue (PR 7 of rework-3.md) was the
   * first surface to read the table directly; this holds every read after it.
   *
   * WHAT THIS DOES NOT PROMISE, and the title used to: that the predicate never
   * leaves the server. The table grant lets any signed-in session ask the API
   * for that column on a visible row. ADR 0017's amendment says why that is
   * accepted; this test is about what the app itself sends.
   */
  const application = () =>
    sourceFiles()
      .filter((f) => f.rel.startsWith('src/') || f.rel.startsWith('app/'))
      .filter((f) => !/\.test\.tsx?$/.test(f.rel));

  it('reads the table with an explicit column list that omits predicate', () => {
    const reads = application().flatMap((f) =>
      [...f.text.matchAll(/from\(\s*['"`]achievements['"`]\s*\)([\s\S]{0,200})/g)].map((m) => ({
        rel: f.rel,
        after: m[1] ?? '',
      }))
    );

    // Not vacuous: the catalogue's read is one of them.
    expect(reads.length).toBeGreaterThan(0);

    for (const { rel, after } of reads) {
      const list = after.match(/^\s*\.select\(\s*'([^']*)'/);
      expect(
        list,
        `${rel}: an achievements read must name its columns in a literal`
      ).not.toBeNull();
      expect(list![1], rel).not.toMatch(/\*|predicate/);
    }
  });

  it('never embeds the table with a star or the predicate from another read', () => {
    /*
     * FOUND IN REVIEW: the test above sees only `from('achievements')`. An
     * embedded resource — `from('achievement_events').select('unlocked_at,
     * achievements (*)')` — passes it, and that is exactly the shape
     * src/db/gamification.ts had until commit f81e591.
     */
    const embeds = application().flatMap((f) =>
      [...f.text.matchAll(/achievements\s*(?:!\w+\s*)?\(([^)]*)\)/g)]
        // A call like `from('achievements')` is not an embed; its "columns" are a quote.
        .filter((m) => !/^\s*['"`]/.test(m[1] ?? ''))
        .map((m) => ({ rel: f.rel, columns: m[1] ?? '' }))
    );

    for (const { rel, columns } of embeds) {
      expect(columns, `${rel}: an embedded achievements read`).not.toMatch(/\*|predicate/);
    }
  });
});

