const ROOT = join(__dirname, '..', '..');
const SEARCH_DIRS = ['src', 'app', 'scripts', 'tests'];
const SKIP_DIRS = new Set(['node_modules', '.next', '.git', 'dist']);

function walk(dir: string): string[] {
  const out: string[] = [];
  for (const entry of readdirSync(dir)) {
    if (SKIP_DIRS.has(entry)) continue;
    const full = join(dir, entry);
    if (statSync(full).isDirectory()) out.push(...walk(full));
    else if (/\.(ts|tsx)$/.test(entry)) out.push(full);
  }
  return out;
}

// WHY: this file names the very strings it searches for, so it must exclude
//       itself or it always fails. This is the only exemption, and it is here
//       rather than in a list of allowed paths so it cannot quietly grow.
const SELF = 'tests/unit/invariants.test.ts';

// Generated by `supabase gen types`, not hand-written. It legitimately contains
// the llm_calls column names, openrouter_id among them. Also ignored by ESLint
// and Prettier for the same reason.
const GENERATED = 'src/db/types.ts';

function sourceFiles(): { path: string; rel: string; text: string }[] {
  return SEARCH_DIRS.flatMap((dir) => {
    try {
      return walk(join(ROOT, dir));
    } catch {
      return [];
    }
  })
    .map((path) => ({
      path,
      rel: relative(ROOT, path).split(sep).join('/'),
      text: readFileSync(path, 'utf8'),
    }))
    .filter((f) => f.rel !== SELF && f.rel !== GENERATED);
}

describe('CLAUDE.md #11 — untrusted text never reaches the instruction channel', () => {
  /*
   * ADR 0005 §1. This is the layer that is a guarantee rather than a
   * mitigation, and it was previously only an AI-NOTE on a database column —
   * which is exactly why it needed to become a test. Nothing failed if someone
   * ignored the comment.
   */
  it('builds no system prompt by interpolation or concatenation', () => {
    // A `system:` property whose value contains ${...} or a + is a per-call
    // string reaching the instruction channel. Static constants are fine.
    const offenders = sourceFiles().flatMap((f) =>
      f.text
        .split('\n')
        .map((line, i) => ({ line, n: i + 1 }))
        .filter(({ line }) => /\bsystem:\s*[^,\n]*(?:\$\{|\s\+\s)/.test(line))
        .map(({ n }) => `${f.rel}:${n}`)
    );

    expect(offenders, 'pass per-call text in messages, never in system — ADR 0005 §1').toEqual([]);
  });

  it('applies the safety preamble inside the gateway, not at call sites', () => {
    // If this moves to call sites, a new stage can forget it — ADR 0005 §3.
    const gateway = sourceFiles().find((f) => f.rel === 'src/llm/gateway.ts');
    expect(gateway?.text).toContain('SAFETY_PREAMBLE');
  });

  it('scans every completion before returning it, and scans what it returns', () => {
    /*
     * FOUND IN REVIEW: this asserted only `toContain('scanOutput')`, which
     * passes with BOTH scans deleted — the word survives in the comments. It is
     * still a substring grep, which is all this file can do, but it now names
     * the two calls and the word that has to be next to them.
     */
    const gateway = sourceFiles().find((f) => f.rel === 'src/llm/gateway.ts');
    expect(gateway?.text).toContain('scanOutput(content)');
    // The parsed value's leaves — ADR 0005's 2026-09-12 amendment. A document
    // scan is not enough; see `scanValue` and its tests for why.
    expect(gateway?.text).toContain('scanValue(validation.value)');
  });
});

